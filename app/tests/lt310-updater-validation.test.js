"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = "app/src/main/java/com/lucianotoscano/pokesearchoverlay/GitHubUpdateCenter.java";
const src = fs.readFileSync(path, "utf8");
assert(src.includes('releases/latest'), "Discovery stays on stable GitHub Releases");
assert(src.includes('CERT.equals(hex(sha.digest(signers[0].toByteArray())))'), "Existing APK certificate pin stays mandatory");
assert(src.includes('release.sha256.equals(hex(sha.digest()))'), "SHA-256 cached verification stays mandatory");
assert(src.includes('!validPackage(context,tmp,release)'), "Downloaded APK archive must pass package/signature checks");
assert(src.includes('if(total!=release.size'), "Exact download length check stays mandatory");
assert(src.includes('private static String downloadFailureMessage(Exception error)'), "Download failures are categorized");
assert(src.includes('error instanceof java.net.SocketTimeoutException'), "Timeout has separate user message");
assert(src.includes('error instanceof java.net.UnknownHostException'), "Offline state has separate message");
assert(src.includes('error instanceof SecurityException'), "Integrity/security error is not suppressed");
assert(!src.includes('cb.report(-1,"Não foi possível validar o APK",null)'), "Generic misleading error removed");
assert(src.includes('cb.report(-1,downloadFailureMessage(e),null)'), "UI receives sanitized cause category");
assert(src.includes('browserFallback.setText("Baixar APK oficial pelo navegador")'), "Alternative route labels official source");
assert(src.includes('browserFallback.setVisibility(android.view.View.VISIBLE);'), "Browser alternative is available even on failure");
assert(src.includes('browserFallback.setOnClickListener(v->openOfficialDownload(activity,release.url))'), "Alternative route opens pinned official release URL");
assert(src.includes('c.setReadTimeout(30000)'), "Allow slower connections to complete large APK transfers");
assert(src.includes('private static final String ASSET_PREFIX="https://github.com/LucianoToscano/PokeSearch/releases/download/";'), "Official URL pattern stays pinned");
console.log("LT310 updater safe diagnostics, browser fallback and pinned integrity checks PASS");
