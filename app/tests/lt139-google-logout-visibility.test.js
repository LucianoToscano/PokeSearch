"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs"),path=require("node:path");
const read=p=>fs.readFileSync(path.join(__dirname,"..",p),"utf8");
const main=read("src/main/java/com/lucianotoscano/pokesearchoverlay/MainActivity.java");
const google=read("src/main/java/com/lucianotoscano/pokesearchoverlay/PremiumGoogleLogin.java");
const start=main.indexOf("private void showPremiumAccountOptions()");
const end=main.indexOf("void promptPremiumDeviceTransfer(",start);
assert.ok(start>0&&end>start,"Premium account menu must exist");
const menu=main.slice(start,end);
assert.ok(menu.includes('.setView(scroll)'),"Premium dialog must use a custom view");
assert.ok(menu.includes('body.addView(signOut'),"Google logout button must be visible");
assert.ok(menu.includes('body.addView(change'),"Google switch button must be visible");
assert.ok(menu.includes('body.addView(transfer'),"Transfer button must remain visible");
assert.ok(menu.includes('signOut.setOnClickListener'),"Logout action must be wired");
assert.ok(menu.includes('logoutPremiumAccount(false);'),"Logout handler must run");
assert.ok(menu.includes('logoutPremiumAccount(true);'),"Switch handler must run");
assert.ok(!menu.includes('.setItems('),"setItems hides actions when setMessage is present");
const a=main.indexOf("private void logoutPremiumAccount(");
const b=main.indexOf("private void showPremiumAccountOptions()",a);
assert.ok(a>0&&b>a);
const logout=main.slice(a,b);
assert.ok(logout.includes('main.postDelayed(localLogout,1500L)'),"Network cannot keep user signed in indefinitely");
assert.ok(logout.includes('PremiumGoogleLogin.signOut('),"Must sign out Firebase");
assert.ok(logout.includes('stopService(new Intent(this,SecondaryOverlayService.class))'),"Must stop P2");
assert.ok(!logout.includes('OverlayService.class);'),"Must not stop free P1");
assert.ok(google.includes('main.postDelayed(finish,1200L)'),"CredentialManager cannot indefinitely block sign-out");
assert.ok(google.includes('auth(activity).signOut();'),"Firebase local sign-out must be immediate");
console.log("PASS LT139: visible Premium account buttons, bounded logout, P1 preserved");
