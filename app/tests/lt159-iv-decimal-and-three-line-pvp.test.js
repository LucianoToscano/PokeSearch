"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs"),path=require("node:path"),vm=require("node:vm");
const assets=path.join(__dirname,"../src/main/assets");
const read=name=>fs.readFileSync(path.join(assets,name),"utf8");
const probe=read("probe.js"),dock=read("dock.html"),detail=read("detail.html");
const visual=require("../src/main/assets/iv_display.js");
const start=probe.indexOf("const POSSIBLE_IV_PERCENT=");
const stop=probe.indexOf("function collect(){",start);
assert.ok(start>=0&&stop>start);
const verify=new Function(probe.slice(start,stop)+"return verifiedCardIv;")();
assert.deepEqual(verify({iv:"14/15/15",ivPercent:"97.8"}),{raw:"14/15/15",percent:98});
assert.deepEqual(verify({iv:"14/15/15",ivPercent:"97,78"}),{raw:"14/15/15",percent:98});
assert.equal(verify({iv:"14/15/15",ivPercent:"96.1"}),null);
assert.deepEqual(verify({iv:"",ivPercent:"97.8"}),{raw:"",percent:98});
assert.equal(verify({iv:"",ivPercent:"99.73"}),null);
assert.ok(probe.includes("const ivMatch=body.match(/(\\d{1,3}(?:[.,]\\d{1,2})?)"),"DOM parser reads decimal source percent");
const dcStart=dock.indexOf("function verifiedSpawnIvPercent(");
const dcEnd=dock.indexOf("function verifiedSpawnRawIv(",dcStart);
assert.ok(dcStart>=0&&dcEnd>dcStart);
const check=new Function(dock.slice(dcStart,dcEnd)+"return verifiedSpawnIvPercent;")();
assert.equal(check({iv:"14/15/15",ivPercent:"97.8"}),98);
assert.equal(check({iv:"",ivPercent:"97.8"}),98);
assert.equal(check({iv:"14/15/15",ivPercent:"99.9"}),null);
assert.equal(check({iv:"",ivPercent:"99.73"}),null);
const half=visual.percentOnly({iv:"",ivPercent:"97.8"});
assert.equal(half.valid,true);
assert.equal(half.raw,"");
assert.equal(half.percent,98);
assert.equal(visual.percentOnly({iv:"16/15/15",ivPercent:"100"}).valid,false);
assert.equal(visual.fromCard({iv:"14/15/15",ivPercent:"97.8"}).valid,true);
assert.equal(visual.colorForEfficiency("92,17"),"#C084FC");
assert.equal(visual.colorForEfficiency("99,73"),"#C084FC");
assert.equal(visual.colorForEfficiency("100,00"),"#F04B70");
const open=detail.indexOf("<script>"),close=detail.indexOf("</script>",open);
assert.ok(open>=0&&close>open);
const script=detail.slice(open+"<script>".length,close);
assert.ok(script);new vm.Script(script);
assert.ok(script.includes("ivSourcePercent=showRaw?null:window.PokeSearchIVDisplay?.percentOnly?.(c)"));
assert.ok(script.includes("h(ivVisual.percent)+'%</span>'"));
assert.ok(detail.includes(".evoLine .evoStatsRow{display:flex"));
assert.ok(detail.includes(".evoLine .evoRankRow{display:grid;grid-template-columns:minmax(0,1fr) minmax(0,1fr)"));
assert.ok(detail.includes("var(--ps-rank-percent-color"));
console.log("LT159 source decimal IV, percentage-only, 3 rows, equal ranks, shared palette PASS");
