"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const dir="app/src/main/java/com/lucianotoscano/pokesearchoverlay/";
const atlas=fs.readFileSync(dir+"EduSpriteAtlas.java","utf8");
const fix=fs.readFileSync(dir+"EduSpritePoseComposer.java","utf8");
const masters=fs.readFileSync(dir+"EduSpriteMasters.java","utf8");
const svc=fs.readFileSync(dir+"RaidDayAssistantOverlayService.java","utf8");

// LT335 substitui o recorte duro anterior que deixava o braço truncado.
// Não modifica em lugar algum os pixels do corpo original da #42.
assert.match(atlas,/if\(EduSpritePoseComposer\.supports\(i\)\)/);
assert.match(atlas,/Bitmap reference=masters\.frame\(42\)/);
assert.match(atlas,/EduSpritePoseComposer\.compose\(reference,i\)/);
assert.match(atlas,/reference\.recycle\(\)/);
assert.match(fix,/canonical\.copy\(Bitmap\.Config\.ARGB_8888,true\)/);
assert.match(fix,/index>=0&&index<=3/);
assert.match(fix,/index==63\|\|index==64/);
assert.match(fix,/drawPokeball\(canvas,p,index\)/);
assert.match(fix,/drawPhone\(canvas,p,index\)/);
assert.match(fix,/clear\(c,p,new int\[\]\[\]\{\{124,272\}/);
assert.match(fix,/PorterDuff\.Mode\.CLEAR/);
assert.match(fix,/c\.drawPath\(path,p\)/);
assert.match(fix,/p\.setAntiAlias\(false\)/);
assert.match(fix,/p\.setFilterBitmap\(false\)/);
assert.doesNotMatch(fix,/gestureRight\(|armEraseRight\(|ARM_SCALE|createScaledBitmap/);
assert.doesNotMatch(atlas,/EduSpriteGeometry512|\.normalize\(original512/i);
assert.match(atlas,/drawable\.setFilterBitmap\(false\)/);
assert.match(atlas,/drawable\.setAntiAlias\(false\)/);
assert.match(atlas,/case "pokebola_gesto": return new int\[\]\{0,1,2,3\}/);
assert.match(atlas,/case "edu_jogando": return new int\[\]\{63,64\}/);
assert.match(atlas,/case "pokebola_gesto": return 220/);
assert.match(masters,/COUNT = 68/);
assert.match(atlas,/SIZES_PX=\{100,150,200\}/);
const idle=svc.match(/private static final String\[\] EDU_IDLE_ROTATION=\{([\s\S]*?)\};/);
assert.ok(idle && idle[1].includes('"pokebola_gesto"') && idle[1].includes('"edu_jogando"'));
const notes=JSON.parse(fs.readFileSync("app/src/main/assets/release_notes.json","utf8"));
const release=notes.releases.find(x=>x.minVersionCode===54539);
assert.ok(release && release.title.includes("0.03.33"),"Notas LT334 históricas preservadas");
console.log("LT334/LT335 PASS: braço sem recorte vertical, gesto e celular com anatomia #42 e nitidez preservada");
