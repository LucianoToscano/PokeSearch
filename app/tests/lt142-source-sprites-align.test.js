"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs"),path=require("node:path"),vm=require("node:vm");
const read=name=>fs.readFileSync(path.join(__dirname,"../src/main/assets",name),"utf8");
const sprites=require("../src/main/assets/sprite_offline.js");
const api=require("../src/main/assets/api_result_contract.js");
const base="file:///android_asset/pokemon-sprites/base/";
const gengar={number:"#94",name:"Gengar",gender:"♀",size:"XS",form:"NORMAL",shiny:false,image:""};
assert.equal(sprites.resolve(gengar).src,base+"94.png");
assert.equal(sprites.resolve({...gengar,shiny:true}).src,"file:///android_asset/pokemon-sprites/shiny/94.png");
const remote="https://pogocoordinates.com/images/pokemon/gengar-94.png";
const dom=sprites.resolve({...gengar,image:remote,imageFromSite:true});
assert.equal(dom.src,remote);
assert.equal(dom.original,base+"94.png");
assert.equal(dom.providerExact,true);
assert.equal(sprites.resolve({...gengar,image:remote,imageFromSite:false}).src,base+"94.png");
assert.equal(sprites.resolve({...gengar,form:"UNKNOWN_GO_COSTUME",costume_id:787,image:""}).src,"");
const mega=sprites.resolve({...gengar,form:"Mega",image:""});
assert.notEqual(mega.src,base+"94.png");
assert.match(mega.original,/10038\.png$/);
const zubat={number:"#41",name:"Zubat",form:"HALLOWEEN_2026_01",shiny:false,image:""};
const costume=sprites.resolve(zubat);
assert.match(costume.src,/pm41\.fHALLOWEEN_2026_01\.icon\.png$/);
assert.notEqual(costume.src,base+"41.png");
assert.match(sprites.resolve({...zubat,shiny:true}).src,/pm41\.fHALLOWEEN_2026_01\.s\.icon\.png$/);
const sameCostume="https://pogocoordinates.com/assets/pokemon/zubat-halloween2026.png";
assert.equal(sprites.resolve({...zubat,image:sameCostume,imageFromSite:true}).src,sameCostume);
assert.match(sprites.resolve({...zubat,image:sameCostume,imageFromSite:true}).original,/pm41\.fHALLOWEEN_2026_01\.icon\.png$/);
assert.equal(api.MAX_RESULTS,100,"Preserve already published VIP100 ceiling");
const probe=read("probe.js"),dock=read("dock.html"),detail=read("detail.html");
new vm.Script(probe);
assert.match(probe,/imageFromSite:siteImageExact/);
assert.match(probe,/const siteImageUrl=image\?candidateImageUrl\(image\):""/);
assert.match(dock,/font-variant-numeric:tabular-nums/);
assert.match(dock,/body\.result-window \.spawnInfoLine\.wrap\{white-space:nowrap/);
assert.match(dock,/vip-results-scroll/);
assert.match(dock,/cards=Array\.isArray\(a\)\?a\.slice\(0,100\)/);
assert.match(detail,/PokeSearchOfflineSprite\.resolve\(c\)/);
console.log("PASS LT142: exact site sprites, Gengar/Zubat, no mismatched variants, VIP100 and baseline alignment");
